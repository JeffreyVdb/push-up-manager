// Run against a disposable local server; this creates test accounts and sets.
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const base = process.env.PUSHUP_TEST_URL || 'http://localhost:5573';
(async () => {
  const browser = await chromium.launch({...(process.env.CHROMIUM_PATH ? {executablePath:process.env.CHROMIUM_PATH} : {}), headless:true, args:['--no-sandbox']});
  try {
    const ctx = await browser.newContext({viewport:{width:1440,height:1000}, reducedMotion:'reduce'});
    const page = await ctx.newPage();
    const errors=[]; page.on('pageerror', error => errors.push(error.message));
    const name = 'browser_'+Date.now(); const password = 'browser-test-password';
    await page.goto(base);
    await page.locator('#gate').waitFor({state:'visible'});
    await page.locator('[data-mode="register"]').click();
    await page.locator('#auth-user').fill(name); await page.locator('#auth-pass').fill(password); await page.locator('#auth-submit').click();
    await page.locator('#app').waitFor({state:'visible'});
    await page.locator('#email-prompt').waitFor({state:'visible'});
    await page.locator('#email-prompt-dismiss').click();
    await page.locator('#email-prompt').waitFor({state:'hidden'});
    await page.evaluate(() => navigator.serviceWorker.ready);
    await page.reload();
    await page.locator('#app').waitFor({state:'visible'});
    await page.waitForFunction(() => document.querySelector('#type-trigger')?.textContent.trim());
    assert.equal(await page.locator('#email-prompt').isVisible(), false);
    console.log('Registration, persistent reminder dismissal and shell install passed');

    const cdp=await ctx.newCDPSession(page);
    await cdp.send('WebAuthn.enable');
    await cdp.send('WebAuthn.addVirtualAuthenticator', {options:{protocol:'ctap2', transport:'internal', hasResidentKey:true, hasUserVerification:true, isUserVerified:true, automaticPresenceSimulation:true}});
    await page.locator('#app [data-open-settings]').click();
    await page.locator('.settings-nav [href="#account-settings"]').click();
    await page.locator('#passkey-name').fill('Test device'); await page.locator('#passkey-password').fill(password);
    await page.locator('#passkey-form button[type=submit]').click();
    await page.waitForFunction(() => document.querySelector('#passkey-status').textContent.includes('Passkey added'));
    assert.match(await page.locator('#passkey-list').innerText(), /Test device/);
    await page.locator('#settings-close').click();
    await page.locator('#logout').click(); await page.locator('#gate').waitFor({state:'visible'});
    await page.locator('#passkey-login').click(); await page.locator('#app').waitFor({state:'visible'});
    await page.waitForFunction(() => document.querySelector('#who').textContent.startsWith('browser_'));
    console.log('Real browser WebAuthn registration and discoverable passkey login passed');

    await ctx.setOffline(true);
    await page.reload(); await page.locator('#app').waitFor({state:'visible'});
    await page.locator('#reps').fill('17'); await page.locator('#log-submit').click();
    await page.waitForFunction(() => document.querySelector('#sync-status').textContent.includes('1 saved set'));
    await page.reload(); await page.locator('#app').waitFor({state:'visible'});
    await page.waitForFunction(() => document.querySelector('#sync-status').textContent.includes('1 saved set'));
    assert.match(await page.locator('#day-entries').innerText(), /17/);
    await ctx.setOffline(false);
    await page.locator('#sync-status button').first().click();
    await page.locator('#sync-status').waitFor({state:'hidden'});
    const snapshot=await (await ctx.request.get(base+'/api/offline')).json();
    assert.equal(snapshot.entries.length,1); assert.equal(snapshot.entries[0].count,17);
    await page.reload(); await page.locator('#app').waitFor({state:'visible'});
    const again=await (await ctx.request.get(base+'/api/offline')).json(); assert.equal(again.entries.length,1);
    console.log('Offline reload, durable set, reconnect and exactly-once sync passed');

    const capture = async name => { if (process.env.PUSHUP_SCREENSHOTS) { fs.mkdirSync(process.env.PUSHUP_SCREENSHOTS,{recursive:true}); await page.screenshot({path:process.env.PUSHUP_SCREENSHOTS+'/'+name+'.png',fullPage:true}); } };
    await page.locator('#app [data-open-settings]').click();
    await capture('settings-desktop');
    await page.locator('#settings-close').click();
    await page.setViewportSize({width:390,height:844});
    await page.reload(); await page.locator('#app').waitFor({state:'visible'});
    await page.locator('#app [data-open-settings]').click();
    await capture('settings-mobile');
    await page.locator('.settings-nav [href="#account-settings"]').click();
    await page.locator('#passkey-form').scrollIntoViewIfNeeded();
    await capture('passkeys-mobile');
    await page.locator('#settings-back').click();
    await page.locator('.settings-nav [href="#appearance-settings"]').click();
    await page.locator('#classic-theme').check();
    await capture('settings-classic-mobile');
    await page.locator('#settings-close').click();
    await page.goto(base+'/forgot-password');
    await page.locator('#recovery').waitFor({state:'visible'});
    await page.locator('#recovery-email').fill('unknown@example.test');
    await page.locator('#recovery-submit').click();
    await page.locator('#recovery-status').waitFor({state:'visible'});
    await capture('recovery-mobile');
    await page.evaluate(() => window.PushupTheme.set('plant'));
    await capture('recovery-plant-mobile');
    await page.goto(base+'/reset-password#token='+ 'A'.repeat(43));
    await page.locator('#recovery').waitFor({state:'visible'});
    assert.equal(new URL(page.url()).hash,'');
    await page.locator('#recovery-password').fill('new-test-password');
    await page.locator('#recovery-repeat').fill('new-test-password');
    await page.locator('#recovery-submit').click();
    await page.locator('#recovery-error').waitFor({state:'visible'});
    assert.match(await page.locator('#recovery-error').innerText(), /invalid|expired/i);
    assert.deepEqual(errors, []);
    console.log('Recovery page routing, fragment privacy, expired reset and no JavaScript errors passed');
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode=1; });
